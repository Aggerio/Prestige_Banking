CREATE TABLE "NOTIFICATION_OUTBOX" (
  "EVENT_ID" VARCHAR2(36) NOT NULL, "EVENT_TYPE" VARCHAR2(80) NOT NULL, "TRANSFER_REFERENCE" VARCHAR2(100) NOT NULL,
  "PAYLOAD" CLOB NOT NULL, "CREATED_AT" TIMESTAMP NOT NULL, "PUBLISHED_AT" TIMESTAMP,
  "ATTEMPTS" NUMBER(10) DEFAULT 0 NOT NULL, CONSTRAINT "PK_NOTIFICATION_OUTBOX" PRIMARY KEY ("EVENT_ID")
);
CREATE INDEX "IDX_NOTIFICATION_OUTBOX_PENDING" ON "NOTIFICATION_OUTBOX" ("PUBLISHED_AT", "CREATED_AT");
CREATE TABLE "NOTIFICATION" (
  "NOTIFICATION_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, "EVENT_ID" VARCHAR2(36) NOT NULL,
  "CUSTOMER_ID" NUMBER NOT NULL, "ROLE" VARCHAR2(20) NOT NULL, "TYPE" VARCHAR2(60) NOT NULL,
  "TITLE" VARCHAR2(160) NOT NULL, "BODY" VARCHAR2(500) NOT NULL, "AMOUNT" NUMBER(15,2) NOT NULL,
  "TRANSFER_REFERENCE" VARCHAR2(100) NOT NULL, "CREATED_AT" TIMESTAMP NOT NULL, "READ_AT" TIMESTAMP,
  CONSTRAINT "PK_NOTIFICATION" PRIMARY KEY ("NOTIFICATION_ID"),
  CONSTRAINT "UQ_NOTIFICATION_EVENT_CUSTOMER_ROLE" UNIQUE ("EVENT_ID", "CUSTOMER_ID", "ROLE")
);
CREATE INDEX "IDX_NOTIFICATION_CUSTOMER_CREATED" ON "NOTIFICATION" ("CUSTOMER_ID", "CREATED_AT" DESC);
CREATE INDEX "IDX_NOTIFICATION_CUSTOMER_UNREAD" ON "NOTIFICATION" ("CUSTOMER_ID", "READ_AT");
