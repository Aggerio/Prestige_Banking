-- Prestige Banking System: canonical Oracle schema and local demo data.
-- Run once in an empty Oracle schema before starting the backend services.

CREATE TABLE bank (
    bank_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    bank_name VARCHAR2(150) NOT NULL,
    ifsc_code VARCHAR2(20) NOT NULL,
    branch_name VARCHAR2(150) NOT NULL,
    customer_count NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT pk_bank PRIMARY KEY (bank_id),
    CONSTRAINT uq_bank_id_ifsc UNIQUE (bank_id, ifsc_code),
    CONSTRAINT uq_bank_ifsc UNIQUE (ifsc_code),
    CONSTRAINT ck_bank_customer_count CHECK (customer_count >= 0)
);

CREATE TABLE customer (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    bank_id NUMBER NOT NULL,
    customer_name VARCHAR2(150) NOT NULL,
    age NUMBER(3) NOT NULL,
    login_password_hash VARCHAR2(255) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_customer PRIMARY KEY (customer_id),
    CONSTRAINT fk_customer_bank FOREIGN KEY (bank_id) REFERENCES bank(bank_id),
    CONSTRAINT ck_customer_age CHECK (age >= 18),
    CONSTRAINT ck_customer_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);

CREATE TABLE address (
    address_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_id NUMBER NOT NULL,
    street_name VARCHAR2(200) NOT NULL,
    city VARCHAR2(100) NOT NULL,
    state VARCHAR2(100) NOT NULL,
    pin_code VARCHAR2(6) NOT NULL,
    CONSTRAINT pk_address PRIMARY KEY (address_id),
    CONSTRAINT fk_address_customer FOREIGN KEY (customer_id) REFERENCES customer(customer_id),
    CONSTRAINT ck_address_pin CHECK (REGEXP_LIKE(pin_code, '^[0-9]{6}$'))
);

CREATE TABLE account (
    account_number VARCHAR2(25) NOT NULL,
    customer_id NUMBER NOT NULL,
    bank_id NUMBER NOT NULL,
    account_type VARCHAR2(20) NOT NULL,
    ifsc_code VARCHAR2(20) NOT NULL,
    transaction_password_hash VARCHAR2(255) NOT NULL,
    account_created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    transfer_limit NUMBER(15,2) NOT NULL,
    minimum_balance NUMBER(15,2) NOT NULL,
    available_balance NUMBER(15,2) NOT NULL,
    account_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_account PRIMARY KEY (account_number),
    CONSTRAINT uq_account_number_ifsc UNIQUE (account_number, ifsc_code),
    CONSTRAINT fk_account_customer FOREIGN KEY (customer_id) REFERENCES customer(customer_id),
    CONSTRAINT fk_account_bank_ifsc FOREIGN KEY (bank_id, ifsc_code) REFERENCES bank(bank_id, ifsc_code),
    CONSTRAINT ck_account_type CHECK (account_type IN ('SAVINGS', 'CURRENT', 'SALARY')),
    CONSTRAINT ck_account_status CHECK (account_status IN ('ACTIVE', 'INACTIVE', 'FROZEN')),
    CONSTRAINT ck_account_amounts CHECK (transfer_limit > 0 AND minimum_balance >= 0 AND available_balance >= 0)
);

-- Cards intentionally contain no customer, account type, or balance copies.
CREATE TABLE card (
    card_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    account_number VARCHAR2(25) NOT NULL,
    card_type VARCHAR2(10) NOT NULL,
    cardholder_name VARCHAR2(150) NOT NULL,
    masked_pan VARCHAR2(24) NOT NULL,
    expiry_month NUMBER(2) NOT NULL,
    expiry_year NUMBER(4) NOT NULL,
    cvv_hash VARCHAR2(255) NOT NULL,
    card_status VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_card PRIMARY KEY (card_id),
    CONSTRAINT uq_card_masked_pan UNIQUE (masked_pan),
    CONSTRAINT fk_card_account FOREIGN KEY (account_number) REFERENCES account(account_number),
    CONSTRAINT ck_card_type CHECK (card_type IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_card_expiry_month CHECK (expiry_month BETWEEN 1 AND 12),
    CONSTRAINT ck_card_expiry_year CHECK (expiry_year BETWEEN 2020 AND 2100),
    CONSTRAINT ck_card_status CHECK (card_status IN ('ACTIVE', 'BLOCKED', 'EXPIRED'))
);

CREATE TABLE fund_transfer (
    transfer_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    idempotency_key VARCHAR2(100) NOT NULL,
    source_account_number VARCHAR2(25) NOT NULL,
    destination_account_number VARCHAR2(25) NOT NULL,
    destination_name VARCHAR2(150) NOT NULL,
    destination_ifsc_code VARCHAR2(20) NOT NULL,
    amount NUMBER(15,2) NOT NULL,
    reference_number VARCHAR2(40) NOT NULL,
    status VARCHAR2(20) NOT NULL,
    request_hash VARCHAR2(64) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    CONSTRAINT pk_fund_transfer PRIMARY KEY (transfer_id),
    CONSTRAINT uq_transfer_reference UNIQUE (reference_number),
    CONSTRAINT uq_transfer_id_reference UNIQUE (transfer_id, reference_number),
    CONSTRAINT uq_transfer_idempotency UNIQUE (source_account_number, idempotency_key),
    CONSTRAINT fk_transfer_source_account FOREIGN KEY (source_account_number) REFERENCES account(account_number),
    CONSTRAINT fk_transfer_destination_account_ifsc FOREIGN KEY (destination_account_number, destination_ifsc_code) REFERENCES account(account_number, ifsc_code),
    CONSTRAINT ck_transfer_amount CHECK (amount > 0),
    CONSTRAINT ck_transfer_different_accounts CHECK (source_account_number <> destination_account_number),
    CONSTRAINT ck_transfer_status CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_transfer_completed_at CHECK ((status = 'COMPLETED' AND completed_at IS NOT NULL) OR (status IN ('PENDING', 'FAILED') AND completed_at IS NULL))
);

CREATE TABLE transaction_details (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    transfer_id NUMBER NOT NULL,
    reference_number VARCHAR2(40) NOT NULL,
    account_number VARCHAR2(25) NOT NULL,
    transaction_type VARCHAR2(10) NOT NULL,
    transaction_amount NUMBER(15,2) NOT NULL,
    transaction_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    bank_id NUMBER NOT NULL,
    ifsc_code VARCHAR2(20) NOT NULL,
    remarks VARCHAR2(250),
    CONSTRAINT pk_transaction_details PRIMARY KEY (transaction_id),
    CONSTRAINT fk_transaction_transfer FOREIGN KEY (transfer_id, reference_number) REFERENCES fund_transfer(transfer_id, reference_number),
    CONSTRAINT fk_transaction_account FOREIGN KEY (account_number) REFERENCES account(account_number),
    CONSTRAINT fk_transaction_bank_ifsc FOREIGN KEY (bank_id, ifsc_code) REFERENCES bank(bank_id, ifsc_code),
    CONSTRAINT ck_transaction_type CHECK (transaction_type IN ('CREDIT', 'DEBIT')),
    CONSTRAINT ck_transaction_amount CHECK (transaction_amount > 0),
    CONSTRAINT uq_transaction_transfer_type UNIQUE (transfer_id, transaction_type)
);

CREATE TABLE password_details (
    password_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_id NUMBER NOT NULL,
    account_number VARCHAR2(25),
    password_type VARCHAR2(20) NOT NULL,
    old_password_hash VARCHAR2(255),
    new_password_hash VARCHAR2(255) NOT NULL,
    password_changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_password_details PRIMARY KEY (password_id),
    CONSTRAINT fk_password_customer FOREIGN KEY (customer_id) REFERENCES customer(customer_id),
    CONSTRAINT fk_password_account FOREIGN KEY (account_number) REFERENCES account(account_number),
    CONSTRAINT ck_password_type CHECK (password_type IN ('LOGIN', 'TRANSACTION')),
    CONSTRAINT ck_password_account_scope CHECK ((password_type = 'LOGIN' AND account_number IS NULL) OR (password_type = 'TRANSACTION' AND account_number IS NOT NULL))
);

-- Refresh-token sessions used by prestige-authentication-service.
CREATE TABLE auth_session (
    session_id VARCHAR2(64) NOT NULL,
    customer_id NUMBER NOT NULL,
    refresh_token_hash VARCHAR2(64) NOT NULL,
    token_family_id VARCHAR2(64) NOT NULL,
    issued_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP,
    last_used_at TIMESTAMP NOT NULL,
    CONSTRAINT pk_auth_session PRIMARY KEY (session_id),
    CONSTRAINT fk_auth_session_customer FOREIGN KEY (customer_id) REFERENCES customer(customer_id)
);

CREATE TABLE public_content (
    content_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    content_type VARCHAR2(20) NOT NULL,
    content_key VARCHAR2(100) NOT NULL,
    title VARCHAR2(200) NOT NULL,
    content_body CLOB,
    image_url VARCHAR2(500),
    contact_email VARCHAR2(150),
    contact_phone VARCHAR2(30),
    display_order NUMBER DEFAULT 1 NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL,
    active_from TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    active_until TIMESTAMP,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_public_content PRIMARY KEY (content_id),
    CONSTRAINT uq_public_content_key UNIQUE (content_key),
    CONSTRAINT ck_public_content_type CHECK (content_type IN ('ABOUT_US', 'CONTACT_US', 'INVESTOR', 'OFFER')),
    CONSTRAINT ck_public_content_active CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT ck_public_content_dates CHECK (active_until IS NULL OR active_until >= active_from)
);

CREATE INDEX idx_customer_bank ON customer(bank_id);
CREATE INDEX idx_account_customer ON account(customer_id);
CREATE INDEX idx_card_account ON card(account_number);
CREATE INDEX idx_transaction_account_date ON transaction_details(account_number, transaction_at DESC);
CREATE INDEX idx_transaction_reference ON transaction_details(reference_number);
CREATE INDEX idx_password_history_customer_type ON password_details(customer_id, password_type, password_changed_at DESC);
CREATE INDEX idx_auth_session_refresh ON auth_session(refresh_token_hash);
CREATE INDEX idx_auth_session_customer ON auth_session(customer_id);
CREATE INDEX idx_fund_transfer_source_created ON fund_transfer(source_account_number, created_at DESC);
CREATE INDEX idx_fund_transfer_destination_created ON fund_transfer(destination_account_number, created_at DESC);
CREATE INDEX idx_public_content_active_order ON public_content(content_type, is_active, display_order);

